// 把 cloudflare/archive-worker 的模組合併成單一檔 worker.bundle.js（給 Cloudflare 後台直接貼上／上傳）。
// 用法：node scripts/bundle-worker.mjs
// 做法：移除相對路徑的 import、把 export 關鍵字拿掉（保留 export default），依相依順序串接。
// 會檢查頂層名稱是否重複，重複就失敗（避免合併後覆蓋函式）。
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'cloudflare', 'archive-worker');
const order = ['auth.js', 'rtc.js', 'squash.js', 'abuse.js', 'worker.js'];

function strip(src) {
  let out = src.replace(/^import\s[\s\S]*?from\s+['"]\.\/[^'"]+['"];?[ \t]*$/gm, '');
  out = out.replace(/^export\s+(?!default\b)(async\s+function|function|const|let|class)\s/gm, '$1 ');
  return out;
}

function topLevelNames(src) {
  const names = [];
  const re = /^(?:async\s+function|function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm;
  let m;
  while ((m = re.exec(src))) names.push(m[1]);
  return names;
}

export function buildBundle() {
  const parts = [];
  const seen = new Map();
  for (const f of order) {
    const src = strip(fs.readFileSync(path.join(dir, f), 'utf8'));
    for (const n of topLevelNames(src)) {
      if (seen.has(n)) throw new Error(`名稱重複：${n}（${seen.get(n)} 與 ${f}）`);
      seen.set(n, f);
    }
    parts.push(`// ---- ${f}\n${src.trim()}\n`);
  }
  const header = [
    '// AUTO-GENERATED by scripts/bundle-worker.mjs — 不要手改；請改 cloudflare/archive-worker 的原始模組後重新產生。',
    '// 這是單一檔案版本，給 Cloudflare 後台直接貼上使用（不需要 wrangler 或 import）。',
    '',
  ].join('\n');
  return { text: header + parts.join('\n'), names: seen.size };
}

export const BUNDLE_PATH = path.join(dir, 'worker.bundle.js');

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { text, names } = buildBundle();
  fs.writeFileSync(BUNDLE_PATH, text);
  console.log(`wrote ${path.relative(root, BUNDLE_PATH)} (${text.length} chars, ${names} top-level names)`);
}
